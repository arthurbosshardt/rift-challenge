import { writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const frontendRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = join(frontendRoot, '..');
const coreDir = join(frontendRoot, 'src/app/core');

let lastUpdatedAt;
try {
  // execFileSync bypasses the shell entirely, so the date format survives
  // as-is on both Windows (cmd.exe) and POSIX shells.
  lastUpdatedAt = execFileSync(
    'git',
    ['log', '-1', '--date=format:%Y-%m-%dT%H:%M', '--format=%cd'],
    { cwd: repoRoot, encoding: 'utf8' },
  ).trim();
} catch {
  lastUpdatedAt = new Date().toISOString().slice(0, 16);
}

const content = `// Generated by scripts/write-last-updated.mjs from the last git commit — do not edit by hand.
export const LAST_UPDATED_AT = '${lastUpdatedAt}';
`;

writeFileSync(join(coreDir, 'last-updated.generated.ts'), content, 'utf8');
console.log('Generated src/app/core/last-updated.generated.ts:', lastUpdatedAt);
